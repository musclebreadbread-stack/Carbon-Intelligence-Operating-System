/**
 * Demo tenant: the emission-factor library.
 *
 * Every factor carries a `sourceId` pointing at a publicly citable publication —
 * IPCC 2006 Guidelines, Korea GIR national factors, UK DESNZ (DEFRA) conversion
 * factors, US EPA eGRID / Emission Factors Hub, US EPA Supply Chain factors — plus
 * one supplier-specific primary-data source. No licensed commercial factor library
 * is used or required.
 *
 * The IPCC-derived combustion factors are computed here from the published
 * kg-per-TJ carbon content and the fuel's net calorific value so the arithmetic is
 * visible rather than copied:
 *
 *     kg gas per unit = (kg gas per TJ) x (NCV in MJ per unit) / 1e6
 *
 * Stationary and mobile combustion factors are separated by `sector` so
 * `resolveFactor` picks the right one for an entry that declares its sector; the
 * grid factors are split into a 2023 and a 2024 validity window so the 24 months
 * of demo activity data genuinely exercise versioned factor resolution.
 */


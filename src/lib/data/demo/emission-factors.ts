/** Gas keys expanded from each combustion spec, in reporting order. */
const COMBUSTION_GASES = ["CO2", "CH4_FOSSIL", "N2O"] as const;

function combustionFactors(): readonly EmissionFactorLike[] {
  const factors: EmissionFactorLike[] = [];
  for (const spec of COMBUSTION_SPECS) {
    const perUnit = ipccPerUnit(spec.rates, spec.ncv);
    for (const gas of COMBUSTION_GASES) {
      factors.push({
        id: `${spec.idPrefix}-${gas.toLowerCase()}`,
        name: `${spec.label} — ${gas}`,
        value: perUnit[gas],
        unit: spec.unit,
        gasType: gas,
        scope: "SCOPE_1",
        scope3Category: null,
        region: spec.region ?? "Global",
        country: spec.country ?? null,
        sector: spec.sector,
        validFrom: new Date(Date.UTC(2020, 0, 1)),
        validTo: null,
        isActive: true,
        uncertainty: spec.uncertainty,
        dataQuality: "MEDIUM",
        organizationId: null,
        sourceId: "demo-efs-ipcc-2006",
        categoryId: spec.categoryId,
        versionId: "demo-efv-ipcc-2006",
      });
    }
  }
  return factors;
}


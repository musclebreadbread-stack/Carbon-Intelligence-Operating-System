/** kg of gas per TJ of net calorific value, IPCC 2006 Vol. 2 defaults. */
type IpccGasRates = { readonly CO2: number; readonly CH4_FOSSIL: number; readonly N2O: number };

/** Converts IPCC kg-per-TJ rates into kg-per-physical-unit factors. */
function ipccPerUnit(rates: IpccGasRates, ncvMjPerUnit: number): IpccGasRates {
  const scale = ncvMjPerUnit / 1_000_000;
  return {
    CO2: roundTo(rates.CO2 * scale, 8),
    CH4_FOSSIL: roundTo(rates.CH4_FOSSIL * scale, 10),
    N2O: roundTo(rates.N2O * scale, 10),
  };
}

